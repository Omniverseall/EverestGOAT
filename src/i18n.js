export function formatStudentDays(days, lang = 'ru') {
  if (!days) return '';
  if (typeof days === 'string') return days;
  if (!Array.isArray(days) || days.length === 0) return '';
  return days
    .map((dayId) => {
      const found = WEEKDAYS.find((w) => w.id === dayId);
      return found ? (found[lang] || found.ru) : dayId;
    })
    .join(', ');
}

